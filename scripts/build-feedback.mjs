import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const required = ['name', 'country_from', 'lang_learning', 'feedback'];
const allowed = new Set([...required, 'short', ...required.map((tag) => `${tag}_en`), 'short_en']);
const filenamePattern = /^(0[1-9]|[1-9][0-9])-[a-z]+(?:-[a-z]+)*\.txt$/;

// This is a plain-text format, not HTML/XML: &, < and > are literal text.
export function parseFeedback(source, filename) {
  const fields = {};
  const text = source.replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
  const blocks = /<([a-z_]+)>\s*([\s\S]*?)<\/\1>/g;
  let end = 0;
  for (const match of text.matchAll(blocks)) {
    if (text.slice(end, match.index).trim())
      throw new Error(`${filename}: текст вне поля или неверный тег.`);
    const [, tag, value] = match;
    if (!allowed.has(tag)) throw new Error(`${filename}: неизвестное поле <${tag}>.`);
    if (Object.hasOwn(fields, tag)) throw new Error(`${filename}: поле <${tag}> повторяется.`);
    if (!value.trim()) throw new Error(`${filename}: поле <${tag}> пустое.`);
    fields[tag] = value.trim();
    end = match.index + match[0].length;
  }
  if (text.slice(end).trim()) throw new Error(`${filename}: текст вне поля или незакрытый тег.`);
  for (const tag of required) {
    if (!fields[tag]) throw new Error(`${filename}: отсутствует поле <${tag}>.`);
  }

  const localized = (tag) => ({ ru: fields[tag], en: fields[`${tag}_en`] || fields[tag] });
  const name = localized('name');
  const country = localized('country_from');
  const language = localized('lang_learning');
  const full = localized('feedback');
  const languageCodes = {
    en: 'en',
    english: 'en',
    английский: 'en',
    fr: 'fr',
    french: 'fr',
    французский: 'fr',
    fi: 'fi',
    finnish: 'fi',
    финский: 'fi'
  };
  const lang = languageCodes[fields.lang_learning.toLowerCase()] || '';
  return {
    name,
    from: { ru: `${country.ru} · ${language.ru}`, en: `${country.en} · ${language.en}` },
    init: Array.from(name.ru)[0].toUpperCase(),
    lang,
    short: {
      ru: fields.short || excerpt(full.ru),
      en:
        fields.short_en ||
        (fields.feedback_en ? excerpt(full.en) : fields.short || excerpt(full.en))
    },
    full
  };
}

function excerpt(text) {
  const characters = Array.from(text.replace(/\s+/g, ' '));
  return characters.length <= 180
    ? characters.join('')
    : `${characters.slice(0, 177).join('').trimEnd()}…`;
}

export async function loadFeedback(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = entries
    .filter((entry) => entry.isFile() && /\.txt$/i.test(entry.name))
    .map((entry) => entry.name)
    .sort();
  if (files.length > 99) throw new Error('В папке feedback допускается максимум 99 отзывов.');
  const numbers = new Set();
  const reviews = [];
  for (const filename of files) {
    const match = filename.match(filenamePattern);
    if (!match)
      throw new Error(
        `${filename}: используйте имя вида 01-alex.txt, номер 01–99 и имя латиницей в нижнем регистре.`
      );
    if (numbers.has(match[1]))
      throw new Error(`${filename}: номер ${match[1]} уже занят другим отзывом.`);
    numbers.add(match[1]);
    reviews.push(parseFeedback(await readFile(path.join(directory, filename), 'utf8'), filename));
  }
  return reviews;
}

export async function buildFeedback(root) {
  const reviews = await loadFeedback(path.join(root, 'feedback'));
  const data = JSON.stringify(reviews, null, 2)
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
  const output = path.join(root, 'js/generated');
  await mkdir(output, { recursive: true });
  await writeFile(
    path.join(output, 'reviews.js'),
    `// Generated by scripts/build-feedback.mjs. Edit feedback/*.txt instead.\nexport default ${data};\n`,
    'utf8'
  );
  return reviews;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('../', import.meta.url));
  try {
    const reviews = await buildFeedback(root);
    console.log(`Отзывы собраны: ${reviews.length}/99.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
